#!/usr/bin/env python3
"""Generate honest, labeled RTL mutants for a normalized Pro-V benchmark.

The output benchmark keeps the original task schema and fills:
  - mutants: list[str] of mutant RTL modules
  - result: list[bool] where True means the mutant is non-equivalent and should
    be killed by a correct/strong testbench; False means equivalent/should pass.

Mutants are generated by small single-site edits in the RTL implementation body
only. Labels are assigned by differential simulation against the reference RTL,
not by assumption.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import sys
from dataclasses import asdict
from typing import Dict, Iterable, List, Tuple

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ["PATH"] = os.path.dirname(sys.executable) + os.pathsep + os.environ.get("PATH", "")

from pro_v.benchmark_adapters import load_benchmark_tasks, write_normalized_benchmark
from pro_v.mutation_strength import classify_mutant


Mutation = Tuple[str, str]


def _split_module_header(verilog: str) -> Tuple[str, str]:
    """Return (prefix_through_module_header, mutable_body)."""
    m = re.search(r"\bmodule\b[\s\S]*?\)\s*;", verilog or "")
    if not m:
        return "", verilog or ""
    return verilog[: m.end()], verilog[m.end() :]


def _replace_one(text: str, start: int, end: int, replacement: str) -> str:
    return text[:start] + replacement + text[end:]


def _operator_mutations(body: str) -> Iterable[Mutation]:
    replacements: Dict[str, List[str]] = {
        "==": ["!="],
        "!=": ["=="],
        "<=": [">="],
        ">=": ["<="],
        "<": [">"],
        ">": ["<"],
        "&&": ["||"],
        "||": ["&&"],
        "&": ["|", "^"],
        "|": ["&", "^"],
        "^": ["&", "|"],
        "+": ["-", "^"],
        "-": ["+", "^"],
    }
    token_re = re.compile(r"==|!=|<=|>=|&&|\|\||[&|^+\-<>]")
    for m in token_re.finditer(body):
        tok = m.group(0)
        # Avoid mutating part-select ranges and numeric signs where possible.
        prev_ch = body[m.start() - 1] if m.start() else ""
        next_ch = body[m.end()] if m.end() < len(body) else ""
        if tok == ":" or (tok in "+-" and (prev_ch in "[({" or next_ch.isdigit())):
            continue
        if tok == "<=":
            line_prefix = body[body.rfind("\n", 0, m.start()) + 1:m.start()]
            stmt_prefix = body[max(body.rfind(";", 0, m.start()), body.rfind("begin", 0, m.start())) + 1:m.start()]
            in_condition = bool(re.search(r"\b(if|else\s+if|while|for)\b", stmt_prefix))
            if not in_condition and re.search(r"[A-Za-z_]\w*(?:\s*\[[^\]]+\])?\s*$", line_prefix):
                continue
        for repl in replacements.get(tok, []):
            yield f"op_{tok}_to_{repl}_{m.start()}", _replace_one(body, m.start(), m.end(), repl)


def _constant_mutations(body: str) -> Iterable[Mutation]:
    based_re = re.compile(r"(?P<w>\d+)?'(?P<base>[bBdDhH])(?P<digits>[0-9a-fA-F_xXzZ]+)")
    for m in based_re.finditer(body):
        base = m.group("base").lower()
        digits = m.group("digits")
        if any(ch in digits for ch in "xXzZ_"):
            continue
        width = int(m.group("w") or "0")
        try:
            value = int(digits, {"b": 2, "d": 10, "h": 16}[base])
        except ValueError:
            continue
        flip_width = width or max(1, value.bit_length())
        for bit in {0, flip_width - 1}:
            new_value = value ^ (1 << bit)
            if width:
                new_value &= (1 << width) - 1
            if base == "b":
                new_digits = format(new_value, f"0{width or len(digits)}b")
            elif base == "h":
                hex_width = max(1, (width + 3) // 4) if width else len(digits)
                new_digits = format(new_value, f"0{hex_width}x")
            else:
                new_digits = str(new_value)
            replacement = f"{m.group('w') or ''}'{m.group('base')}{new_digits}"
            yield f"const_{m.group(0)}_bit{bit}_{m.start()}", _replace_one(body, m.start(), m.end(), replacement)

    plain_re = re.compile(r"(?<![\w'])\d+(?![\w'])")
    for m in plain_re.finditer(body):
        value = int(m.group(0))
        if value > 4096:
            continue
        for new_value in sorted({value ^ 1, value + 1, max(0, value - 1)}):
            if new_value == value:
                continue
            yield f"num_{value}_to_{new_value}_{m.start()}", _replace_one(body, m.start(), m.end(), str(new_value))


def _assignment_mutations(body: str) -> Iterable[Mutation]:
    assign_re = re.compile(r"\bassign\s+(?P<lhs>[^=;]+?)=\s*(?P<rhs>[^;]+);")
    for m in assign_re.finditer(body):
        rhs = m.group("rhs").strip()
        if not rhs:
            continue
        replacement = body[m.start() : m.start("rhs")] + f"~({rhs})" + body[m.end("rhs") : m.end()]
        yield f"assign_invert_{m.start()}", _replace_one(body, m.start(), m.end(), replacement)


def generate_candidate_mutants(module_code: str) -> Iterable[Mutation]:
    prefix, body = _split_module_header(module_code)
    seen = {module_code}
    for name, new_body in list(_operator_mutations(body)) + list(_constant_mutations(body)) + list(_assignment_mutations(body)):
        mutant = prefix + new_body
        if mutant in seen or mutant == module_code:
            continue
        seen.add(mutant)
        yield name, mutant


def infer_circuit_type(task: dict) -> str:
    ctype = str(task.get("circuit_type") or "").lower()
    header = task.get("header") or task.get("module_code") or ""
    header_is_seq = bool(re.search(r"\b(?:clk\w*|\w*_clk|clock\w*)\b|@\s*\([^)]*(?:posedge|negedge)", header, re.I | re.S))
    if header_is_seq:
        return "SEQ"
    if ctype in {"cmb", "comb", "combinational"}:
        return "CMB"
    if ctype in {"seq", "sequential"}:
        return "SEQ"
    return "CMB"


def add_mutants_to_task(task: dict, args) -> Tuple[dict, dict]:
    out = copy.deepcopy(task)
    module_code = out.get("module_code") or ""
    ctype = infer_circuit_type(out)
    mutants: List[str] = []
    labels: List[bool] = []
    details = []

    for mutation_name, mutant_code in generate_candidate_mutants(module_code):
        if len(mutants) >= args.max_mutants:
            break
        verdict = classify_mutant(
            module_code,
            mutant_code,
            ctype,
            max_exhaustive_bits=args.max_exhaustive_bits,
            random_samples=args.random_samples,
            seq_trials=args.seq_trials,
            seq_cycles=args.seq_cycles,
            timeout=args.timeout,
        )
        record = {
            "mutation": mutation_name,
            "equivalent": verdict.equivalent,
            "certain": verdict.certain,
            "unknown": verdict.unknown,
            "error": verdict.error[:500] if verdict.error else "",
            "witness_count": len(verdict.witnesses),
        }
        if verdict.unknown and not args.include_unknown:
            details.append({**record, "kept": False})
            continue
        mutants.append(mutant_code)
        labels.append(not verdict.equivalent if not verdict.unknown else True)
        details.append({**record, "kept": True})

    out["mutants"] = mutants
    out["result"] = labels
    return out, {
        "task_number": out.get("task_number"),
        "task_id": out.get("task_id"),
        "circuit_type": ctype,
        "mutants_kept": len(mutants),
        "non_equivalent": sum(1 for x in labels if x),
        "equivalent": sum(1 for x in labels if not x),
        "details": details,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("input_benchmark")
    ap.add_argument("output_benchmark")
    ap.add_argument("--benchmark_format", default="auto")
    ap.add_argument("--max_mutants", type=int, default=10)
    ap.add_argument("--task_numbers", default="")
    ap.add_argument("--max_exhaustive_bits", type=int, default=12)
    ap.add_argument("--random_samples", type=int, default=20000)
    ap.add_argument("--seq_trials", type=int, default=80)
    ap.add_argument("--seq_cycles", type=int, default=128)
    ap.add_argument("--timeout", type=int, default=180)
    ap.add_argument("--include_unknown", action="store_true")
    ap.add_argument("--report", default="")
    args = ap.parse_args()

    tasks = load_benchmark_tasks(args.input_benchmark, args.benchmark_format)
    selected = None
    if args.task_numbers.strip():
        selected = {int(x) for x in re.split(r"[, ]+", args.task_numbers.strip()) if x}

    out_tasks = []
    report = {
        "input_benchmark": args.input_benchmark,
        "output_benchmark": args.output_benchmark,
        "max_mutants": args.max_mutants,
        "tasks": [],
    }
    for task in tasks:
        if selected is not None and int(task.get("task_number", -1)) not in selected:
            out_tasks.append(task)
            continue
        mutated, item_report = add_mutants_to_task(task, args)
        print(
            f"task {item_report['task_number']}: kept {item_report['mutants_kept']} "
            f"mutants ({item_report['non_equivalent']} non-equivalent, "
            f"{item_report['equivalent']} equivalent)"
        )
        out_tasks.append(mutated)
        report["tasks"].append(item_report)

    write_normalized_benchmark(out_tasks, args.output_benchmark)
    report_path = args.report or args.output_benchmark + ".mutation_report.json"
    with open(report_path, "w") as f:
        json.dump(report, f, indent=2)
    print(f"wrote {args.output_benchmark}")
    print(f"wrote {report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
